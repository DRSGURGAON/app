package `in`.docsafe.crypto

import java.nio.ByteBuffer
import javax.crypto.AEADBadTagException
import javax.crypto.Cipher
import javax.crypto.Mac
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Wraps (encrypts) and unwraps small secrets such as per-file data encryption keys. */
interface KeyWrapper {
    fun wrap(plainKey: ByteArray, associatedData: ByteArray): ByteArray

    /** @throws IntegrityException if the blob or associated data was modified. */
    fun unwrap(blob: ByteArray, associatedData: ByteArray): ByteArray
}

/**
 * AES-256-GCM key wrapper around a [SecretKey] supplied lazily.
 *
 * On Android the supplier returns a non-exportable Android Keystore key; the IV is
 * generated by the provider (Keystore enforces randomized encryption), so this
 * class never chooses IVs itself. In JVM tests a software key is used.
 *
 * Blob layout: version(1) | ivLength(1) | iv | ciphertext+tag(16)
 */
class AesGcmKeyWrapper(private val keySupplier: () -> SecretKey) : KeyWrapper {
    override fun wrap(plainKey: ByteArray, associatedData: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        try {
            cipher.init(Cipher.ENCRYPT_MODE, keySupplier())
        } catch (e: java.security.GeneralSecurityException) {
            throw KeyUnavailableException("Wrapping key unavailable", e)
        }
        cipher.updateAAD(associatedData)
        val ct = cipher.doFinal(plainKey)
        val iv = cipher.iv ?: throw KeyUnavailableException("Provider did not generate an IV")
        require(iv.size in 12..32) { "Unexpected IV length" }
        return ByteBuffer.allocate(2 + iv.size + ct.size)
            .put(VERSION).put(iv.size.toByte()).put(iv).put(ct).array()
    }

    override fun unwrap(blob: ByteArray, associatedData: ByteArray): ByteArray {
        if (blob.size < 2 + 12 + TAG_BYTES || blob[0] != VERSION) throw IntegrityException("Malformed wrapped key")
        val ivLen = blob[1].toInt() and 0xFF
        if (ivLen !in 12..32 || blob.size < 2 + ivLen + TAG_BYTES) throw IntegrityException("Malformed wrapped key")
        val cipher = Cipher.getInstance(TRANSFORMATION)
        try {
            cipher.init(Cipher.DECRYPT_MODE, keySupplier(), GCMParameterSpec(TAG_BYTES * 8, blob, 2, ivLen))
        } catch (e: java.security.GeneralSecurityException) {
            throw KeyUnavailableException("Wrapping key unavailable", e)
        }
        cipher.updateAAD(associatedData)
        return try {
            cipher.doFinal(blob, 2 + ivLen, blob.size - 2 - ivLen)
        } catch (e: AEADBadTagException) {
            throw IntegrityException("Wrapped key failed authentication", e)
        }
    }

    private companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val TAG_BYTES = 16
        const val VERSION: Byte = 1
    }
}

/** Creates initialised HMAC-SHA256 instances. On Android the key lives in the Keystore. */
fun interface MacFactory {
    fun newMac(): Mac
}

/** [MacFactory] backed by a [SecretKey] (Keystore or software). */
class HmacSha256Factory(private val keySupplier: () -> SecretKey) : MacFactory {
    override fun newMac(): Mac = try {
        Mac.getInstance("HmacSHA256").apply { init(keySupplier()) }
    } catch (e: java.security.GeneralSecurityException) {
        throw KeyUnavailableException("MAC key unavailable", e)
    }
}
