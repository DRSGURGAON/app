"""Document Scanner Pro mark -> Android vector drawables (+ a PNG preview).

The mark, in unit coordinates of the square tile (0..1): a white document page
with a folded corner and three text lines, gold scan-frame corners around it
and a gold scan line across it. lib/app/widgets/brand_mark.dart (LogoMark)
draws the same shapes. Run from the repo root:  python3 tool/brand/make_icon.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable")

WHITE, FOLD, LINE, GOLD, NAVY = "#FFFFFFFF", "#FFB9C1FF", "#FFC5CCF2", "#FFF2B53A", "#FF15215C"

# Page (with the folded top-right corner cut off).
PL, PT, PR, PB, FOLDSZ, RAD = 0.33, 0.25, 0.67, 0.77, 0.10, 0.03
# Text lines (x0, x1, y, height).
LINES = [(0.39, 0.61, 0.40, 0.03), (0.39, 0.61, 0.62, 0.03), (0.39, 0.53, 0.69, 0.03)]
# Scan line.
SCAN = (0.24, 0.76, 0.505, 0.035)
# Frame corners: box, arm length, thickness.
BOX = (0.20, 0.16, 0.80, 0.86)
ARM, THICK = 0.12, 0.045


def page_path(m):
    x = lambda u: m(u, 0)[0]
    y = lambda v: m(0, v)[1]
    f = lambda v: f"{v:.2f}"
    return (
        f"M{f(x(PL + RAD))},{f(y(PT))} L{f(x(PR - FOLDSZ))},{f(y(PT))} L{f(x(PR))},{f(y(PT + FOLDSZ))} "
        f"L{f(x(PR))},{f(y(PB - RAD))} Q{f(x(PR))},{f(y(PB))} {f(x(PR - RAD))},{f(y(PB))} "
        f"L{f(x(PL + RAD))},{f(y(PB))} Q{f(x(PL))},{f(y(PB))} {f(x(PL))},{f(y(PB - RAD))} "
        f"L{f(x(PL))},{f(y(PT + RAD))} Q{f(x(PL))},{f(y(PT))} {f(x(PL + RAD))},{f(y(PT))} Z"
    )


def rect(m, x0, y0, x1, y1):
    a, b = m(x0, y0), m(x1, y1)
    return f"M{a[0]:.2f},{a[1]:.2f} L{b[0]:.2f},{a[1]:.2f} L{b[0]:.2f},{b[1]:.2f} L{a[0]:.2f},{b[1]:.2f} Z"


def fold_path(m):
    a, b, c = m(PR - FOLDSZ, PT), m(PR - FOLDSZ, PT + FOLDSZ), m(PR, PT + FOLDSZ)
    return f"M{a[0]:.2f},{a[1]:.2f} L{b[0]:.2f},{b[1]:.2f} L{c[0]:.2f},{c[1]:.2f} Z"


def corners_path(m):
    l, t, r, b = BOX
    parts = []
    for (cx, cy, dx, dy) in [(l, t, 1, 1), (r, t, -1, 1), (l, b, 1, -1), (r, b, -1, -1)]:
        # Horizontal arm and vertical arm of each L.
        parts.append(rect(m, min(cx, cx + dx * ARM), min(cy, cy + dy * THICK), max(cx, cx + dx * ARM), max(cy, cy + dy * THICK)))
        parts.append(rect(m, min(cx, cx + dx * THICK), min(cy, cy + dy * ARM), max(cx, cx + dx * THICK), max(cy, cy + dy * ARM)))
    return " ".join(parts)


def bar(m, spec):
    x0, x1, y, h = spec
    return rect(m, x0, y, x1, y + h)


def vector(size, viewport, body, comment):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} Generated by tool/brand/make_icon.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp" android:height="{size}dp"\n'
        f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
        + body
        + "</vector>\n"
    )


def p(color, data, even_odd=False):
    fill = ' android:fillType="evenOdd"' if even_odd else ""
    return f'    <path android:fillColor="{color}"{fill} android:pathData="{data}" />\n'


def full_mark(m):
    return (
        p(WHITE, page_path(m))
        + p(FOLD, fold_path(m))
        + "".join(p(LINE, bar(m, ln)) for ln in LINES)
        + p(GOLD, bar(m, SCAN))
        + p(GOLD, corners_path(m))
    )


def main():
    # Adaptive icon: the tile maps to 14..94 of the 108 dp canvas (safe zone).
    adaptive = lambda u, v: (14 + 80 * u, 14 + 80 * v)
    files = {
        "ic_launcher_foreground.xml": vector(108, 108, full_mark(adaptive), "Document Scanner Pro mark: page, scan frame and scan line."),
        "ic_launcher_monochrome.xml": vector(
            108, 108,
            # One colour: page with the scan line cut out, plus the frame corners.
            p(WHITE, page_path(adaptive) + " " + bar(adaptive, (PL - 0.01, PR + 0.01, SCAN[2], SCAN[3])), even_odd=True)
            + p(WHITE, corners_path(adaptive)),
            "Themed (monochrome) icon for Android 13+.",
        ),
        "splash_logo.xml": vector(
            96, 96,
            p("#26FFFFFF", "M26.88,0 H69.12 A26.88,26.88 0 0 1 96,26.88 V69.12 A26.88,26.88 0 0 1 69.12,96 H26.88 A26.88,26.88 0 0 1 0,69.12 V26.88 A26.88,26.88 0 0 1 26.88,0 Z")
            + full_mark(lambda u, v: (96 * u, 96 * v)),
            "Splash mark on a translucent tile.",
        ),
        "ic_stat_docsafe.xml": vector(
            24, 24,
            p(WHITE, page_path(lambda u, v: (24 * u, 24 * v)) + " " + bar(lambda u, v: (24 * u, 24 * v), (PL - 0.01, PR + 0.01, SCAN[2] - 0.01, SCAN[3] + 0.02)), even_odd=True)
            + p(WHITE, corners_path(lambda u, v: (24 * u, 24 * v))),
            "Monochrome status-bar icon.",
        ),
    }
    for name, xml in files.items():
        with open(os.path.join(RES, name), "w") as f:
            f.write(xml)
        print(name)
    if len(sys.argv) > 1:
        preview(sys.argv[1])


def preview(out):
    """PNG preview of the mark on the brand gradient (for review only)."""
    from PIL import Image, ImageDraw
    s = 512
    img = Image.new("RGB", (s, s))
    d = ImageDraw.Draw(img)
    for y in range(s):
        t = y / s
        d.line([(0, y), (s, y)], fill=(int(11 + 20 * t), int(20 + 26 * t), int(55 + 67 * t)))
    m = lambda u, v: (s * u, s * v)
    def poly(pts, color):
        d.polygon([m(*q) for q in pts], fill=color)
    poly([(PL, PT), (PR - FOLDSZ, PT), (PR, PT + FOLDSZ), (PR, PB), (PL, PB)], "#FFFFFF")
    poly([(PR - FOLDSZ, PT), (PR - FOLDSZ, PT + FOLDSZ), (PR, PT + FOLDSZ)], "#B9C1FF")
    for x0, x1, y, h in LINES:
        d.rectangle([m(x0, y), m(x1, y + h)], fill="#C5CCF2")
    x0, x1, y, h = SCAN
    d.rectangle([m(x0, y), m(x1, y + h)], fill="#F2B53A")
    l, t, r, b = BOX
    for (cx, cy, dx, dy) in [(l, t, 1, 1), (r, t, -1, 1), (l, b, 1, -1), (r, b, -1, -1)]:
        d.rectangle([m(min(cx, cx + dx * ARM), min(cy, cy + dy * THICK)), m(max(cx, cx + dx * ARM), max(cy, cy + dy * THICK))], fill="#F2B53A")
        d.rectangle([m(min(cx, cx + dx * THICK), min(cy, cy + dy * ARM)), m(max(cx, cx + dx * THICK), max(cy, cy + dy * ARM))], fill="#F2B53A")
    img.save(out)


if __name__ == "__main__":
    main()
