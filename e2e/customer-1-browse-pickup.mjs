import { createRequire } from 'node:module';
const require = createRequire(process.env.PLAYWRIGHT_NODE_PATH ?? '/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const OUT = (process.env.SHOTS_DIR ?? '/tmp/ardh-shots');
const BASE = 'http://localhost:8099';
const b = await chromium.launch({ args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'en-IN' });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text().slice(0, 200)); });
page.on('response', (r) => { if (r.status() >= 400 && r.url().includes(':4010')) errors.push(`http ${r.status()} ${r.request().method()} ${r.url().replace('http://localhost:4010', '')}`); });
const T = (t, o) => page.getByText(t, o).first();
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
const go = async (p) => { await page.goto(BASE + p, { waitUntil: 'networkidle' }); };
let failed = 0;
const step = async (n, fn) => { try { await fn(); console.log('ok  ', n); } catch (e) { failed++; console.log('FAIL', n, '-', e.message.slice(0, 500)); await shot('fail-' + n.replace(/\W+/g, '_')).catch(() => {}); } };

await go('/');
await step('home loads (Hindi default)', async () => { await T('श्रेणी के अनुसार खरीदें').waitFor({ timeout: 10000 }); await shot('01-home-hi'); });
await step('switch to English', async () => { await go('/account'); await T('English', { exact: true }).click(); await go('/'); await T('Shop by category').waitFor(); await shot('02-home-en'); });
await step('categories show Stationery + subcategories', async () => { await go('/categories'); await T('Stationery & School Supplies').click(); await T('Notebooks & Registers').waitFor(); await shot('03-categories-expanded'); });
await step('subcategory product list', async () => { await T('Notebooks & Registers').click(); await T('[SAMPLE] Notebook 172 pages (Pack of 6)').waitFor({ timeout: 10000 }); await shot('04-products'); });
await step('add to cart + stepper', async () => { await page.getByRole('button', { name: /Add \[SAMPLE\] Notebook/ }).click(); await page.getByLabel('Increase quantity').first().waitFor(); await page.getByLabel('Increase quantity').first().click(); await shot('05-added'); });
await step('product detail', async () => { await T('[SAMPLE] Notebook 172 pages (Pack of 6)').click(); await T('Inclusive of all taxes').waitFor({ timeout: 8000 }); await shot('06-product'); });
await step('cart below minimum', async () => { await go('/cart'); await T(/more to place your order/).waitFor({ timeout: 8000 }); await shot('07-cart-below-min'); });
await step('cart meets minimum', async () => { for (let i = 0; i < 2; i++) { await page.getByLabel('Increase quantity').first().click(); await page.waitForTimeout(200); } await T('Minimum order met').waitFor({ timeout: 8000 }); await shot('08-cart-ok'); });
await step('login with OTP', async () => {
  await page.getByRole('button', { name: /Proceed to checkout/ }).click();
  await T('Please login to continue').waitFor();
  await page.getByRole('button', { name: 'Login' }).click();
  await page.getByPlaceholder('98XXXXXXXX').fill('9876500011');
  await page.getByRole('button', { name: 'Send OTP' }).click();
  const dev = await T(/Development OTP: \d{6}/).textContent();
  await shot('09-otp');
  await page.getByLabel('Enter OTP').fill(dev.match(/\d{6}/)[0]);
  await page.getByRole('button', { name: /Verify/ }).click();
  await T('Bill details').waitFor({ timeout: 10000 });
});
await step('checkout pickup shows free delivery fee', async () => { await T('Store pickup', { exact: true }).click(); await T('To pay').waitFor({ timeout: 10000 }); await shot('10-checkout-pickup'); });
await step('delivery without address is blocked', async () => { await T('Home delivery', { exact: true }).click(); await T('Add a delivery address to continue').waitFor(); await shot('11-checkout-delivery-noaddr'); });
await step('place pickup COD order', async () => { await T('Store pickup', { exact: true }).click(); await T('To pay').waitFor(); await page.getByRole('button', { name: 'Place order' }).click(); await T('Order placed!').waitFor({ timeout: 15000 }); await shot('12-order-placed'); });
await step('my orders lists it', async () => { await go('/orders'); await T(/Order ARD/).waitFor({ timeout: 8000 }); await shot('13-orders'); });
console.log('browser/API errors:', errors.slice(0, 10));
console.log(failed ? `${failed} step(s) failed` : 'all steps passed');
await b.close();
